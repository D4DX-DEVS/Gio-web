-- Groups reproduce the headings and order on /team/, /district-leaders/, /former-leaders/.
CREATE TABLE leader_groups (
  id          INTEGER PRIMARY KEY,
  scope       TEXT NOT NULL CHECK (scope IN ('state','district','former')),
  heading     TEXT,                             -- exactly as published, e.g. a section heading, a district name, or a term "1984 - 1985"
