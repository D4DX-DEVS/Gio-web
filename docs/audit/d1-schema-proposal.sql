-- 4. Page sections (homepage and every other "sections" page): draft rows + published snapshot
------------------------------------------------------------------------------
-- Editors work on these rows (the draft). "Publish" validates every section with its Zod schema,
-- writes one JSON snapshot to published_layouts, and the public site reads only that snapshot.
CREATE TABLE sections (
  id          INTEGER PRIMARY KEY,
  page_id     INTEGER NOT NULL REFERENCES pages(id),
  type        TEXT NOT NULL CHECK (type IN (
                'hero_carousel','image_banner','image','rich_text','instagram_feed','poster_slider',
                'featured_video','logo_carousel','embed','map','contact_form','document_list','cta',
                'latest_posts','upcoming_events')),
  title       TEXT,                             -- admin label; shown publicly only if data_json says so
  data_json   TEXT NOT NULL DEFAULT '{}',       -- type-specific settings (autoplay, interval, youtube_id, html, iframe_src, ...)
  sort        INTEGER NOT NULL,
  is_visible  INTEGER NOT NULL DEFAULT 1,
  starts_at   INTEGER,                          -- optional schedule window
  ends_at     INTEGER,
  legacy_ref  TEXT,                             -- e.g. 'elementor:2074:<element id>' when the DB dump provides it
  source TEXT NOT NULL, source_ref TEXT, import_run_id INTEGER, review_state TEXT NOT NULL DEFAULT 'verified',
  created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL
);
CREATE INDEX sections_page_sort ON sections(page_id, sort);

CREATE TABLE section_items (                    -- slides, posters, logos, gallery images, buttons
  id          INTEGER PRIMARY KEY,
  section_id  INTEGER NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
  media_id    INTEGER REFERENCES media(id),
  heading     TEXT,
  body        TEXT,
  link_url    TEXT,                             -- NULL where the live slide has no link (all 7 hero slides today)
  link_label  TEXT,
  open_in_new_tab INTEGER NOT NULL DEFAULT 0,
  alt_text    TEXT,                             -- overrides media.alt_text for this placement
  sort        INTEGER NOT NULL,
  is_visible  INTEGER NOT NULL DEFAULT 1,
  starts_at   INTEGER,
  ends_at     INTEGER,
  source TEXT NOT NULL, source_ref TEXT, import_run_id INTEGER, review_state TEXT NOT NULL DEFAULT 'verified',
  created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL
);
CREATE INDEX section_items_section_sort ON section_items(section_id, sort);

CREATE TABLE published_layouts (
  id            INTEGER PRIMARY KEY,
  page_id       INTEGER NOT NULL REFERENCES pages(id),
  layout_json   TEXT NOT NULL,                  -- resolved sections + items + media URLs, ready to render
  is_current    INTEGER NOT NULL DEFAULT 0,
  published_by  TEXT,
  published_at  INTEGER NOT NULL
);
CREATE UNIQUE INDEX published_layouts_current ON published_layouts(page_id) WHERE is_current = 1;

