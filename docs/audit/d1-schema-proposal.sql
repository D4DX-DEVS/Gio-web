-- 8. URLs: legacy map, redirects, 404 log
------------------------------------------------------------------------------
-- One row per old URL (139 from the audit + generated patterns + anything found later).
CREATE TABLE legacy_urls (
  id               INTEGER PRIMARY KEY,
  old_path         TEXT NOT NULL UNIQUE,        -- percent-encoded exactly as WordPress emitted it (lowercase hex)
  old_path_decoded TEXT NOT NULL,
  legacy_type      TEXT NOT NULL,               -- 'post','page','event','taxonomy-archive','theme-demo-cpt', ...
  live_status      INTEGER,                     -- status seen in the audit (200, 500)
  in_sitemap       TEXT,
  action           TEXT NOT NULL CHECK (action IN ('same_path','redirect_301','gone_410','pending_decision')),
  new_path         TEXT,                        -- set when action = same_path or redirect_301
  entity_type      TEXT,                        -- what now serves it
  entity_id        INTEGER,
  decision_status  TEXT NOT NULL CHECK (decision_status IN ('verified','needs_client_approval','client_approved')),
  decided_by       TEXT,
  decided_at       INTEGER,
  note             TEXT,
  last_verified_at INTEGER,                     -- set by the verification script after a successful check
  last_verified_status INTEGER
);

-- What middleware actually enforces. Built from legacy_urls (approved rows) + admin edits + slug changes.
CREATE TABLE redirects (
  id          INTEGER PRIMARY KEY,
  from_path   TEXT NOT NULL UNIQUE,
  to_path     TEXT,                             -- NULL with status 410
  status_code INTEGER NOT NULL DEFAULT 301 CHECK (status_code IN (301,302,308,410)),
  origin      TEXT NOT NULL CHECK (origin IN ('migration','slug_change','manual')),
  legacy_url_id INTEGER REFERENCES legacy_urls(id),
  hits        INTEGER NOT NULL DEFAULT 0,
  last_hit_at INTEGER,
  note        TEXT,
  created_at  INTEGER NOT NULL
);

CREATE TABLE not_found_log (                    -- catches old URLs we missed, after launch
  path TEXT PRIMARY KEY, hits INTEGER NOT NULL DEFAULT 1, referrer TEXT, first_seen_at INTEGER NOT NULL, last_seen_at INTEGER NOT NULL
);

------------------------------------------------------------------------------
-- 9. Migration bookkeeping and client review queue
------------------------------------------------------------------------------
CREATE TABLE import_runs (
  id              INTEGER PRIMARY KEY,
  source_kind     TEXT NOT NULL,                -- 'rest_snapshot','wxr','sql_dump','uploads_archive','html_snapshot'
  source_label    TEXT NOT NULL,                -- e.g. 'snapshot-2026-10-27'
  source_sha256   TEXT,
  mode            TEXT NOT NULL CHECK (mode IN ('dry_run','apply','delta')),
  started_at      INTEGER NOT NULL,
  finished_at     INTEGER,
  status          TEXT NOT NULL CHECK (status IN ('running','succeeded','failed')),
  counts_json     TEXT,
  report_r2_key   TEXT                          -- gio-private/migration-reports/<run>/report.json
);

-- Idempotency: one row per legacy object, so re-running updates instead of duplicating.
CREATE TABLE import_items (
  legacy_key     TEXT PRIMARY KEY,              -- 'wp:post:2938', 'file:wp-content/uploads/2025/08/bnr1.jpg', 'html:leader:/team/#3'
  entity_type    TEXT NOT NULL,
  entity_id      INTEGER,
  content_sha256 TEXT NOT NULL,                 -- hash of the normalised source record; unchanged hash = skip
  first_run_id   INTEGER NOT NULL REFERENCES import_runs(id),
  last_run_id    INTEGER NOT NULL REFERENCES import_runs(id),
  warnings_json  TEXT
);

-- Field-level disagreements between sources (e.g. REST title vs DB title). Never auto-resolved.
CREATE TABLE import_conflicts (
  id INTEGER PRIMARY KEY, run_id INTEGER NOT NULL REFERENCES import_runs(id),
  legacy_key TEXT NOT NULL, field TEXT NOT NULL, values_json TEXT NOT NULL,  -- {"wp_sql": "...", "wp_rest": "..."}
  chosen_source TEXT, resolved_by TEXT, resolved_at INTEGER
);

-- Everything that needs a client decision, visible in the admin dashboard.
CREATE TABLE review_items (
  id             INTEGER PRIMARY KEY,
  code           TEXT NOT NULL,                 -- 'Q1','Q3','D4', ...
  entity_type    TEXT,
  entity_id      TEXT,
  field          TEXT,
  current_value  TEXT,                          -- exactly as published
  suggested_value TEXT,                         -- only when the client or evidence supplies one; never guessed
  evidence       TEXT,                          -- URL / file / screenshot reference
  status         TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','keep_as_is','change_approved','rejected')),
  decided_by     TEXT,
  decided_at     INTEGER,
  created_at     INTEGER NOT NULL
);

