-- GIO Kerala: proposed Cloudflare D1 (SQLite) schema
-- Status: PROPOSAL, not applied anywhere. Depends on decision D1 (database = D1).
-- In implementation this becomes Drizzle schema files + drizzle-kit migrations; this file is the reviewable spec.
--
-- Conventions
--   * Timestamps are INTEGER unix milliseconds (UTC). Display timezone is Asia/Kolkata.
--   * Every imported row carries provenance: source, source_ref, import_run_id, review_state.
--       source       'wp_sql' | 'wp_wxr' | 'wp_rest' | 'html_parse' | 'css_parse' | 'file_probe' | 'manual'
--       source_ref   stable legacy key, e.g. 'wp:post:2938', 'html:team:/team/#3', 'file:wp-content/uploads/2025/08/bnr1.jpg'
--       review_state 'verified'           = matches public evidence, migrate as-is
--                    'pending_client'     = imported as published today, but flagged for a client decision (see review_items)
--                    'client_approved'    = client decided; value now final
--   * Nothing from the theme-demo set is inserted into content tables until decision D4 is made.
--     Those URLs live only in legacy_urls (action 'pending_decision') and in the private R2 archive.

PRAGMA foreign_keys = ON;

------------------------------------------------------------------------------
-- 1. Identity, roles, audit
------------------------------------------------------------------------------
-- Better Auth owns: user, session, account, verification, two_factor (generated by its CLI).
-- We extend its `user` table with a role column and keep our own role checks server-side.
--   user.role TEXT NOT NULL DEFAULT 'contributor' CHECK (role IN ('owner','admin','editor','contributor'))
--   user.is_active INTEGER NOT NULL DEFAULT 1

-- Legacy WordPress authors are bylines, NOT login accounts. Passwords and emails are never migrated.
CREATE TABLE authors (
  id            INTEGER PRIMARY KEY,
  display_name  TEXT NOT NULL,                 -- 'Editor GIO', 'Editor' (exactly as in WP)
  slug          TEXT NOT NULL UNIQUE,          -- 'gioadmin', 'gioeditor'
  user_id       TEXT REFERENCES user(id),      -- optional link to a real admin account later
  legacy_wp_id  INTEGER UNIQUE,
  source TEXT NOT NULL, source_ref TEXT, import_run_id INTEGER, review_state TEXT NOT NULL DEFAULT 'verified',
  created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL
);

CREATE TABLE audit_log (
  id          INTEGER PRIMARY KEY,
  user_id     TEXT,                            -- NULL for importer runs
  action      TEXT NOT NULL,                   -- 'create','update','publish','unpublish','delete','restore','login', ...
  entity_type TEXT NOT NULL,
  entity_id   TEXT NOT NULL,
  summary     TEXT,
  diff_json   TEXT,
  ip_hash     TEXT,
  created_at  INTEGER NOT NULL
);
CREATE INDEX audit_log_entity ON audit_log(entity_type, entity_id, created_at);

CREATE TABLE revisions (
  id            INTEGER PRIMARY KEY,
  entity_type   TEXT NOT NULL,                 -- 'post','page','event','leader','site_settings', ...
  entity_id     TEXT NOT NULL,
  snapshot_json TEXT NOT NULL,
  user_id       TEXT,
  created_at    INTEGER NOT NULL
);
CREATE INDEX revisions_entity ON revisions(entity_type, entity_id, created_at);

------------------------------------------------------------------------------
-- 2. Media (R2 objects) and documents
------------------------------------------------------------------------------
CREATE TABLE media (
  id                  INTEGER PRIMARY KEY,
  r2_bucket           TEXT NOT NULL DEFAULT 'gio-media',
  r2_key              TEXT NOT NULL UNIQUE,     -- legacy: 'wp-content/uploads/2025/08/bnr1.jpg' (byte-exact path)
  kind                TEXT NOT NULL CHECK (kind IN ('image','document','video','other')),
  usage_hint          TEXT,                     -- 'banner','leader_photo','logo','post_image','document' (admin filter only)
  original_filename   TEXT NOT NULL,
  mime_type           TEXT NOT NULL,            -- sniffed from bytes, not trusted from WP (2 items are mislabelled text/xml)
  declared_mime_type  TEXT,                     -- what WordPress said, kept for the audit trail
  byte_size           INTEGER NOT NULL,
  width               INTEGER,
  height              INTEGER,
  sha256              TEXT NOT NULL,
  alt_text            TEXT,                     -- NULL = never provided (do not invent)
  caption             TEXT,
  title               TEXT,
  credit              TEXT,
  -- WordPress keeps several physical files per attachment. Each physical file is its own row;
  -- variant rows point at the attachment's primary row.
  variant_of_media_id INTEGER REFERENCES media(id),
  variant_role        TEXT CHECK (variant_role IN ('wp_scaled','wp_unscaled_original','wp_pre_edit_original')),
  legacy_wp_id        INTEGER,                  -- attachment ID; NULL for the 17 files the API does not list until the DB dump fills it
  legacy_url          TEXT UNIQUE,
  is_public           INTEGER NOT NULL DEFAULT 1,
  uploaded_by         TEXT,
  source TEXT NOT NULL, source_ref TEXT, import_run_id INTEGER, review_state TEXT NOT NULL DEFAULT 'verified',
  created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL,
  deleted_at INTEGER
);
CREATE INDEX media_legacy_wp_id ON media(legacy_wp_id);
CREATE INDEX media_sha256 ON media(sha256);

-- Where each file is used. Drives "used on" in admin, blocks deletion while in use, and verification D3/D4.
CREATE TABLE media_usage (
  media_id    INTEGER NOT NULL REFERENCES media(id),
  entity_type TEXT NOT NULL,                    -- 'post','page','section_item','leader','event','site_settings','css_background'
  entity_id   TEXT NOT NULL,
  field       TEXT NOT NULL,                    -- 'featured','inline','slide','photo','logo','background', ...
  PRIMARY KEY (media_id, entity_type, entity_id, field)
);

CREATE TABLE documents (
  id           INTEGER PRIMARY KEY,
  media_id     INTEGER NOT NULL REFERENCES media(id),
  title        TEXT NOT NULL,
  description  TEXT,
  category     TEXT,                            -- 'call_for_papers','brochure','report', ...
  status       TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','archived')),
  published_at INTEGER,
  sort         INTEGER NOT NULL DEFAULT 0,
  source TEXT NOT NULL, source_ref TEXT, import_run_id INTEGER, review_state TEXT NOT NULL DEFAULT 'verified',
  created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL
);

