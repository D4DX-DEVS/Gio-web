CREATE TABLE posts (
  id                 INTEGER PRIMARY KEY,
  slug               TEXT NOT NULL UNIQUE,      -- decoded UTF-8 (NFC is NOT applied; bytes kept as WP stored them)
  title              TEXT NOT NULL DEFAULT '',  -- post 2577 is legitimately empty today (Q1)
  excerpt            TEXT,
  body_html          TEXT NOT NULL,             -- sanitized
  body_json          TEXT,                      -- TipTap JSON once edited in the new admin; NULL for untouched legacy posts
  legacy_body_html   TEXT,                      -- raw content.rendered as imported, never shown publicly, for verification
  featured_media_id  INTEGER REFERENCES media(id),
  author_id          INTEGER REFERENCES authors(id),
  status             TEXT NOT NULL CHECK (status IN ('draft','review','scheduled','published','private','archived')),
  published_at       INTEGER,
  modified_at        INTEGER,
  locale             TEXT NOT NULL DEFAULT 'ml',
  seo_title          TEXT,
  seo_description    TEXT,
  og_media_id        INTEGER REFERENCES media(id),
  comments_open      INTEGER NOT NULL DEFAULT 0,
  legacy_wp_id       INTEGER UNIQUE,
  legacy_url         TEXT,
  source TEXT NOT NULL, source_ref TEXT, import_run_id INTEGER, review_state TEXT NOT NULL DEFAULT 'verified',
  created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL,
  deleted_at INTEGER
);
CREATE INDEX posts_status_published ON posts(status, published_at DESC);

CREATE TABLE post_categories (post_id INTEGER NOT NULL REFERENCES posts(id), category_id INTEGER NOT NULL REFERENCES categories(id), PRIMARY KEY (post_id, category_id));
CREATE TABLE post_tags       (post_id INTEGER NOT NULL REFERENCES posts(id), tag_id      INTEGER NOT NULL REFERENCES tags(id),       PRIMARY KEY (post_id, tag_id));

CREATE TABLE pages (
  id               INTEGER PRIMARY KEY,
  slug             TEXT NOT NULL UNIQUE,        -- '' for the homepage
  title            TEXT NOT NULL,
  template         TEXT NOT NULL DEFAULT 'sections', -- 'sections','leaders','post_listing','contact','embed'
  template_config  TEXT,                        -- JSON, e.g. {"leader_scope":"state"} or {"category":"gio-news","per_page":9}
  status           TEXT NOT NULL CHECK (status IN ('draft','published','private','archived')),
  published_at     INTEGER,
  seo_title        TEXT,
  seo_description  TEXT,
  og_media_id      INTEGER REFERENCES media(id),
  show_in_sitemap  INTEGER NOT NULL DEFAULT 1,
  legacy_wp_id     INTEGER UNIQUE,
  legacy_url       TEXT,
  source TEXT NOT NULL, source_ref TEXT, import_run_id INTEGER, review_state TEXT NOT NULL DEFAULT 'verified',
  created_at INTEGER NOT NULL, updated_at INTEGER NOT NULL,
  deleted_at INTEGER
);

